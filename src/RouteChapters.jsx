const icons = [ClipboardList, Ruler, PackageCheck];
const layoutFor = {
  contacts: 'rail', schedule: 'steps', about: 'cards', favorites: 'cards', compare: 'rail',
  cart: 'cards', checkout: 'steps', account: 'rail', services: 'steps', catalog: 'cards', product: 'rail',
};

export function RouteChapters({section, detail, product, remaining}) {
  const chapters = product ? productChapters(product,remaining) :
    section === 'services' && detail ? serviceChapters(detail) : guides[section];
  if (!chapters) return null;
  const layout = layoutFor[section];
  return <div className={'route-chapters chapter-layout-' + layout}>
    {chapters.map(([title,rows,link],index) => {
      const Icon = icons[index % icons.length];
      return <section className="block route-chapter" key={title}>
        <div className="chapter-lead"><Icon size={34}/><h2>{title}</h2>
          {link && <a className="outline chapter-link" href={link[1]}>{link[0]}<ArrowUpRight size={16}/></a>}
        </div>
        <ul className="chapter-items">{rows.map(([name,description]) =>
          <li key={name}><Check className="chapter-check" size={19}/><div><h3>{name}</h3><p>{description}</p></div></li>
        )}</ul>
      </section>;
    })}
  </div>;
}

